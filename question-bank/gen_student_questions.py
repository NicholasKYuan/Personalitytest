for q_data in NEW_QUESTIONS:
    stem = q_data[0]
    cat = q_data[1]
    states = q_data[2]
    scale_type = q_data[3]
    diff = q_data[4]
    opts_or_map = q_data[5]
    themes = q_data[6]
    reverse = q_data[7] if len(q_data) > 7 else False

    # 检查重复
    ns = normalize(stem)
    if ns in existing_stems:
        skipped += 1
        continue

    # 构建 options
    if scale_type == 'fc':
        options = [{'text': t, 'score': s} for t, s in opts_or_map]
    else:  # likert-4
        sm = opts_or_map
        options = [
            {'text': '非常不符合', 'score': {k: v[0] for k, v in sm.items()}},
            {'text': '不太符合', 'score': {k: v[1] for k, v in sm.items()}},
            {'text': '比较符合', 'score': {k: v[2] for k, v in sm.items()}},
            {'text': '非常符合', 'score': {k: v[3] for k, v in sm.items()}},
        ]

    # 从score推导systems字段
    systems = set()
    for o in options:
        for k in o['score']:
            systems.add(k.split('.')[0])
    # gallup themes 存在则加上 gallup
    if themes:
        systems.add('gallup')

    item = {
        'id': f'Q{qid:04d}',
        'stem': stem,
        'category': cat,
        'scale': 'forced-choice' if scale_type == 'fc' else 'likert-4',
        'difficulty': diff,
        'reverse': reverse,
        'applicable_states': states,
        'systems': sorted(systems),
        'options': options,
        'gallup_themes': themes,
    }
    output_items.append(item)
    existing_stems.add(ns)
    qid += 1

