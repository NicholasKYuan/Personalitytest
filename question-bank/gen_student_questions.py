# ========== 加载现有题库 ==========
BANK_PATH = 'items.jsonl'
existing = []
existing_stems = set()

def normalize(s):
    s = re.sub(r'[，。？！,. ?！]', '', s)
    s = re.sub(r'[（(][^）)]*[）)]', '', s)
    s = s.replace('②', '').strip()
    s = re.sub(r'[你我]$', '', s)
    s = re.sub(r'时$', '', s)
    return s

with open(BANK_PATH, 'r', encoding='utf-8') as f:
    for line in f:
        if line.strip():
            it = json.loads(line)
            existing.append(it)
            existing_stems.add(normalize(it['stem']))

max_id = max(int(it['id'][1:]) for it in existing)
